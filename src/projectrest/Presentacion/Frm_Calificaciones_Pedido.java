    private void listar(String texto) {
        TblPedidos.setModel(this.CONTROL.listar(texto));
        TableRowSorter orden = new TableRowSorter(TblPedidos.getModel());
        TblPedidos.setRowSorter(orden);
        
        int[] columnas = {0, 1, 3, 5};
        this.ocultarColumnas(columnas);
    }
    
    private void ocultarColumnas(int[] columns) {
        for (int col : columns) {
            TblPedidos.getColumnModel().getColumn(col).setMaxWidth(0);
            TblPedidos.getColumnModel().getColumn(col).setMinWidth(0);
            TblPedidos.getTableHeader().getColumnModel().getColumn(col).setMaxWidth(0);
            TblPedidos.getTableHeader().getColumnModel().getColumn(col).setMinWidth(0);
        }
    }

