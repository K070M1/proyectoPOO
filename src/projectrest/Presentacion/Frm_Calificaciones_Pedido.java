    private void BtnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSeleccionarActionPerformed
        if (TblPedidos.getSelectedRowCount() == 1) {
            String id = String.valueOf(TblPedidos.getValueAt(TblPedidos.getSelectedRow(), 0));
            String cliente = String.valueOf(TblPedidos.getValueAt(TblPedidos.getSelectedRow(), 4));
            String fecha = String.valueOf(TblPedidos.getValueAt(TblPedidos.getSelectedRow(), 10));
            String total = String.valueOf(TblPedidos.getValueAt(TblPedidos.getSelectedRow(), 11));
            
            this.vista.TxtIdPedido.setText(id);
            this.vista.TxtPedidoLabel.setText(fecha + " | " + cliente + ", S/" + total);
            this.setVisible(false);
        } else {
            JOptionPane.showMessageDialog(null, "Debe seleccionar un Pedido de la lista primero..!");
        }
    }//GEN-LAST:event_BtnSeleccionarActionPerformed


